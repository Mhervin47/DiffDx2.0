    appointment_id: Mapped[uuid.UUID] = mapped_column(
        GUID, ForeignKey("appointments.id", ondelete="CASCADE"), nullable=False, unique=True
    )
    specialty: Mapped[str] = mapped_column(String(100), nullable=False)
    to_doctor: Mapped[str | None] = mapped_column(String(200))  # blank = any available specialist
    urgency: Mapped[str] = mapped_column(String(50), nullable=False, server_default="Routine")
    notes: Mapped[str | None] = mapped_column(Text)
    internal_note: Mapped[str | None] = mapped_column(Text)  # doctor-only, never returned to patients
    referred_at: Mapped[datetime] = mapped_column(server_default=func.now(), nullable=False)

    appointment: Mapped["Appointment"] = relationship()


